pub(crate) fn ambiguous_unicode_violations(ctx: &FileCtx<'_>) -> Vec<Violation> {
    let mut out = Vec::new();

    for (i, line) in ctx.lines.iter().enumerate() {
        if line.is_ascii() {
            continue;
        }

        for ch in line.chars() {
            if ch.is_ascii() {
                continue;
            }

            if let Ok(idx) = CONFUSABLES.binary_search_by_key(&ch, |&(c, _)| c) {
                let Some((_, looks_like)) = CONFUSABLES.get(idx) else {
                    continue;
                };

                out.push(violation(
                    ctx.rel,
                    i + 1,
                    format!(
                        "ambiguous Unicode character U+{:04X} (confusable with {looks_like:?})",
                        ch as u32
                    ),
                ));
                break;
            }
        }
    }

    out
}

pub(crate) fn bidirectional_unicode_violations(ctx: &FileCtx<'_>) -> Vec<Violation> {
    ctx.lines
        .iter()
        .enumerate()
        .filter_map(|(index, line)| {
            let control = line.chars().find(|ch| BIDI_CONTROLS.contains(ch))?;

            Some(violation(
                ctx.rel,
                index + 1,
                format!(
                    "bidirectional Unicode control character U+{:04X} (trojan-source risk)",
                    control as u32
                ),
            ))
        })
        .collect()
}
